export type ClientSafeHttpFieldIssue = {
  field: string;
  code?: string;
};

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

function sanitizeClientSafeFieldIssues(
  value: unknown,
): ClientSafeHttpFieldIssue[] | undefined {
  if (!Array.isArray(value)) {
    return undefined;
  }
  const issues: ClientSafeHttpFieldIssue[] = [];
  for (const row of value) {
    if (!isRecord(row) || typeof row.field !== 'string') {
      continue;
    }
    const issue: ClientSafeHttpFieldIssue = { field: row.field };
    if (typeof row.code === 'string') {
      issue.code = row.code;
    }
    issues.push(issue);
  }
  return issues.length > 0 ? issues : undefined;
}

/**
 * Structured response fragments forwarded for specific client-safe codes. Values are validated before
 * inclusion so operational gates can return field-level guidance without exposing arbitrary internals.
 */
export const CLIENT_SAFE_HTTP_ERROR_STRUCTURED_DETAIL_KEYS: Partial<
  Record<string, readonly string[]>
> = {
  VEHICLE_LISTING_NOT_READY: ['field_issues'],
};

/**
 * Body fields, beyond `code` and `message`, that the global filter forwards for a client-safe code. Only IDs and
 * order numbers belong here, and a field is forwarded only when its value is a string.
 */
export const CLIENT_SAFE_HTTP_ERROR_DETAIL_KEYS: Partial<
  Record<string, readonly string[]>
> = {
  VEHICLE_HAS_ACTIVE_ORDER: ['orderId', 'orderNumber'],
};

export function isClientSafeOperationalHttpError(
  responseBody: Record<string, unknown>,
): boolean {
  const code = responseBody.code;
  return typeof code === 'string' && CLIENT_SAFE_HTTP_ERROR_CODES.has(code);
}

export function pickClientSafeHttpErrorDetails(
  responseBody: Record<string, unknown>,
): Record<string, string> {
  return pickClientSafeHttpErrorParams(responseBody);
}

/** Typed `params` object for client-safe codes (allowlisted string fields only). */
export function pickClientSafeHttpErrorParams(
  responseBody: Record<string, unknown>,
): Record<string, string> {
  const code = responseBody.code;
  if (typeof code !== 'string' || !CLIENT_SAFE_HTTP_ERROR_CODES.has(code)) {
    return {};
  }

  const params: Record<string, string> = {};
  for (const key of CLIENT_SAFE_HTTP_ERROR_DETAIL_KEYS[code] ?? []) {
    const topLevel = responseBody[key];
    if (typeof topLevel === 'string') {
      params[key] = topLevel;
      continue;
    }
    const nested = isRecord(responseBody.params)
      ? responseBody.params[key]
      : undefined;
    if (typeof nested === 'string') {
      params[key] = nested;
    }
  }
  return params;
}

export function pickClientSafeHttpErrorStructuredDetails(
  responseBody: Record<string, unknown>,
): Record<string, unknown> {
  const code = responseBody.code;
  if (typeof code !== 'string' || !CLIENT_SAFE_HTTP_ERROR_CODES.has(code)) {
    return {};
  }

  const structured: Record<string, unknown> = {};
  for (const key of CLIENT_SAFE_HTTP_ERROR_STRUCTURED_DETAIL_KEYS[code] ?? []) {
    if (key === 'field_issues') {
      const fieldIssues = sanitizeClientSafeFieldIssues(
        responseBody.field_issues,
      );
      if (fieldIssues) {
        structured.field_issues = fieldIssues;
      }
    }
  }
  return structured;
}
