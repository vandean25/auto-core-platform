/** Normative column order and enum tokens from migration-csv-format*.md (1.0 / 1.1). */

export type MigrationCsvFileName = `${string}.csv`;

export type MigrationCsvColumnSpec = {
  name: string;
  requiredValue: boolean;
  enumValues?: readonly string[];
};

export type MigrationCsvFileSpec = {
  countsKey: string;
  columns: readonly MigrationCsvColumnSpec[];
};

const boolCol = (name: string, requiredValue: boolean) => ({
  name,
  requiredValue,
});
const enumCol = (
  name: string,
  requiredValue: boolean,
  enumValues: readonly string[],
) => ({
  name,
  requiredValue,
  enumValues,
});
const col = (name: string, requiredValue: boolean) => ({
  name,
  requiredValue,
});

