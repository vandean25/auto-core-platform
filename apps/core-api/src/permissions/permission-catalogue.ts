export type PermissionDefinition = {
  id: PermissionId;
  label: { de: string; en: string };
};

export const PERMISSION_CATALOGUE: readonly PermissionDefinition[] =
  DEFINITIONS.map(([id, de, en]) => ({ id, label: { de, en } }));

const PERMISSION_IDS: ReadonlySet<string> = new Set(
  DEFINITIONS.map(([id]) => id),
);

export function isPermissionId(value: string): value is PermissionId {
  return PERMISSION_IDS.has(value);
}
