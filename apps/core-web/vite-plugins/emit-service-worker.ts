import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { Plugin } from 'vite'
import { runKillSwitch, runServiceWorker } from '../src/pwa/service-worker.ts'

/** The text of `dist/sw.js`: the real service worker for `version`, or the kill switch that removes it. */
export function buildServiceWorkerSource(version: string, killSwitch: boolean): string {
  const body = killSwitch
    ? `(${runKillSwitch.toString()})(self);`
    : `(${runServiceWorker.toString()})(self, ${JSON.stringify(version)});`
  return `// Generated by the build (AUT-740). Do not edit.\n${body}\n`
}

/**
 * Writes dist/sw.js at the root (never under /assets, so Firebase Hosting can serve it with no-cache and the
 * root scope). The cache name carries the release (the git tag in Cloud Build, else the Sentry release), so
 * every release ships a different worker file. With PWA_KILL_SWITCH=true the worker is the self-removing variant.
 */
export function emitServiceWorkerPlugin(appVersion: string, env: Record<string, string>): Plugin {
  const version = appVersion.trim() || process.env.SENTRY_RELEASE || 'dev'
  const killSwitch = (env.PWA_KILL_SWITCH ?? process.env.PWA_KILL_SWITCH) === 'true'
  let outDir = 'dist'

  return {
    name: 'emit-service-worker',
    configResolved(config) {
      outDir = config.build.outDir
    },
    closeBundle() {
      mkdirSync(outDir, { recursive: true })
      writeFileSync(join(outDir, 'sw.js'), buildServiceWorkerSource(version, killSwitch), 'utf8')
    },
  }
}
