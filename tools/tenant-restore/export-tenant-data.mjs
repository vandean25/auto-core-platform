#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { spawnSync } from 'node:child_process';

import {
  buildTenantRestoreManifest,
  renderExportQuery,
} from './tenant-schema.mjs';

const UUID_PATTERN =
  /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$/;
const schemaPath = path.resolve(
  import.meta.dirname,
  '../../apps/core-api/prisma/schema.prisma',
);

function quoteIdentifier(identifier) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function publicTable(table) {
  return `public.${quoteIdentifier(table)}`;
}

function quoteLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function runPsql(databaseUrl, tenantId, sql) {
  const result = spawnSync(
    'psql',
    [
      databaseUrl,
      '-X',
      '-q',
      '-At',
      '-v',
      'ON_ERROR_STOP=1',
      '-v',
      `target_tenant_id=${tenantId}`,
      '-c',
      sql,
    ],
    { encoding: 'utf8' },
  );

  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(result.stderr || `psql exited with status ${result.status}`);
  }
  return result.stdout;
}

function runWithTenantContext(databaseUrl, tenantId, query) {
  const tenantContext = `DO $tenant_restore$
BEGIN
  PERFORM set_config('app.target_tenant_id', ${quoteLiteral(tenantId)}, false);
END
$tenant_restore$;`;
  const tenantScopedQuery = query.replaceAll(
    ":'target_tenant_id'",
    "current_setting('app.target_tenant_id')",
  );
  return runPsql(
    databaseUrl,
    tenantId,
    `${tenantContext}
${tenantScopedQuery}`,
  );
}

function verifyTenantParentLinks(databaseUrl, tenantId, manifest) {
  const tenantTables = new Set(
    manifest.definitions
      .filter((definition) => definition.kind === 'tenant')
      .map((definition) => definition.table),
  );

  for (const foreignKey of manifest.foreignKeys) {
    if (
      !tenantTables.has(foreignKey.childTable) ||
      !tenantTables.has(foreignKey.parentTable) ||
      foreignKey.childColumns.includes('tenant_id')
    ) {
      continue;
    }

    const keyMatches = foreignKey.childColumns
      .map(
        (column, index) =>
          `parent.${quoteIdentifier(
            foreignKey.parentColumns[index],
          )} = child.${quoteIdentifier(column)}`,
      )
      .join(' AND ');
    const nonNullKeys = foreignKey.childColumns
      .map((column) => `child.${quoteIdentifier(column)} IS NOT NULL`)
      .join(' AND ');
    const invalidRows = runWithTenantContext(
      databaseUrl,
      tenantId,
      `SELECT count(*)
         FROM ${publicTable(foreignKey.childTable)} AS child
        WHERE child."tenant_id" = current_setting('app.target_tenant_id')
          AND ${nonNullKeys}
          AND NOT EXISTS (
            SELECT 1
              FROM ${publicTable(foreignKey.parentTable)} AS parent
             WHERE ${keyMatches}
               AND parent."tenant_id" = current_setting('app.target_tenant_id')
          );`,
    ).trim();

    if (invalidRows !== '0') {
      throw new Error(
        `cross-tenant parent link detected: ${foreignKey.childTable} -> ${foreignKey.parentTable}`,
      );
    }
  }
}

function columnsForTable(databaseUrl, tenantId, table) {
  const columns = runPsql(
    databaseUrl,
    tenantId,
    `SELECT column_name
       FROM information_schema.columns
      WHERE table_schema = 'public'
        AND table_name = ${`'${table.replaceAll("'", "''")}'`}
      ORDER BY ordinal_position;`,
  ).trim().split('\n').filter(Boolean);

  if (columns.length === 0) {
    throw new Error(`No columns found for restore table ${table}`);
  }
  return columns;
}

function writeExport(databaseUrl, tenantId, outputPath) {
  const schema = fs.readFileSync(schemaPath, 'utf8');
  const manifest = buildTenantRestoreManifest(schema);
  const outputDirectory = path.dirname(path.resolve(outputPath));
  fs.mkdirSync(outputDirectory, { recursive: true });
  verifyTenantParentLinks(databaseUrl, tenantId, manifest);
  const selfReferencesByTable = new Map();
  for (const reference of manifest.selfReferences) {
    const references = selfReferencesByTable.get(reference.table) ?? [];
    references.push(reference);
    selfReferencesByTable.set(reference.table, references);
  }
  const selfRestoreStages = new Map();

  const chunks = [
    '-- Generated by tools/tenant-restore/export-tenant-data.sh.\n',
    `-- TENANT_ID: ${tenantId}\n`,
    '-- Every COPY source is tenant-filtered; this is not a pg_dump output.\n',
    '\\if :{?tenant_restore_in_transaction}\n',
    '\\else\n',
    'BEGIN;\n',
    '\\endif\n\n',
  ];

  for (const definition of manifest.definitions) {
    const columns = columnsForTable(databaseUrl, tenantId, definition.table);
    const selfReferences = selfReferencesByTable.get(definition.table) ?? [];
    let nullColumns = [];

    if (selfReferences.length > 0) {
      const stageName = `tenant_restore_self_${selfRestoreStages.size}`;
      const stageColumns = [
        ...new Set([
          ...selfReferences[0].keyColumns,
          ...selfReferences.flatMap((reference) => reference.columns),
        ]),
      ];
      selfRestoreStages.set(definition.table, {
        stageName,
        keyColumns: selfReferences[0].keyColumns,
        references: selfReferences,
      });
      nullColumns = selfReferences.flatMap(
        (reference) => reference.columns,
      );
      chunks.push(
        `CREATE TEMP TABLE pg_temp.${quoteIdentifier(
          stageName,
        )} AS SELECT ${stageColumns
          .map(quoteIdentifier)
          .join(', ')} FROM ${publicTable(definition.table)} WITH NO DATA;\n`,
      );
      chunks.push(
        `COPY pg_temp.${quoteIdentifier(stageName)} (${stageColumns
          .map(quoteIdentifier)
          .join(', ')}) FROM STDIN WITH (FORMAT csv);\n`,
      );
      chunks.push(
        runWithTenantContext(
          databaseUrl,
          tenantId,
          renderExportQuery(definition, { columns: stageColumns }),
        ),
      );
      chunks.push('\\.\n\n');
    }

    chunks.push(
      `COPY public.${quoteIdentifier(definition.table)} (${columns
        .map(quoteIdentifier)
        .join(', ')}) FROM STDIN WITH (FORMAT csv);\n`,
    );
    chunks.push(
      runWithTenantContext(
        databaseUrl,
        tenantId,
        renderExportQuery(definition, {
          columns,
          nullColumns,
        }),
      ),
    );
    chunks.push('\\.\n\n');
  }

  for (const [table, stage] of selfRestoreStages) {
    chunks.push(
      `UPDATE ${publicTable(table)} AS target SET ${stage.references
        .flatMap((reference) =>
          reference.columns.map(
            (column) =>
              `${quoteIdentifier(column)} = stage.${quoteIdentifier(column)}`,
          ),
        )
        .join(', ')} FROM pg_temp.${quoteIdentifier(
        stage.stageName,
      )} AS stage WHERE ${stage.keyColumns
        .map(
          (column) =>
            `target.${quoteIdentifier(column)} = stage.${quoteIdentifier(
              column,
            )}`,
        )
        .join(' AND ')};

`,
    );
  }

  chunks.push(
    '\\if :{?tenant_restore_in_transaction}\n',
    '\\else\n',
    'COMMIT;\n',
    '\\endif\n',
  );
  fs.writeFileSync(outputPath, chunks.join(''));
}

const [, , databaseUrl, tenantId, outputPath] = process.argv;
if (!databaseUrl || !tenantId || !outputPath) {
  process.stderr.write(
    'Usage: export-tenant-data.mjs <database_url> <tenant_id> <output_sql_file>\n',
  );
  process.exit(1);
}
if (!UUID_PATTERN.test(tenantId)) {
  process.stderr.write('target tenant id must be a UUID\n');
  process.exit(1);
}

try {
  writeExport(databaseUrl, tenantId, outputPath);
} catch (error) {
  process.stderr.write(`[tenant-restore] ${error.message}\n`);
  process.exitCode = 1;
}
