#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { spawnSync } from 'node:child_process';

import {
  buildTenantRestoreManifest,
  renderExportQuery,
} from './tenant-schema.mjs';

const UUID_PATTERN =
  /^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$/;
const schemaPath = path.resolve(
  import.meta.dirname,
  '../../apps/core-api/prisma/schema.prisma',
);

function quoteIdentifier(identifier) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function quoteLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function runPsql(databaseUrl, tenantId, sql) {
  const result = spawnSync(
    'psql',
    [
      databaseUrl,
      '-X',
      '-q',
      '-At',
      '-v',
      'ON_ERROR_STOP=1',
      '-v',
      `target_tenant_id=${tenantId}`,
      '-c',
      sql,
    ],
    { encoding: 'utf8' },
  );

  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(result.stderr || `psql exited with status ${result.status}`);
  }
  return result.stdout;
}

function copyForTenant(databaseUrl, tenantId, query) {
  const tenantContext = `DO $tenant_restore$
BEGIN
  PERFORM set_config('app.target_tenant_id', ${quoteLiteral(tenantId)}, false);
END
$tenant_restore$;`;
  const tenantScopedQuery = query.replaceAll(
    ":'target_tenant_id'",
    "current_setting('app.target_tenant_id')",
  );
  return runPsql(
    databaseUrl,
    tenantId,
    `${tenantContext}
${tenantScopedQuery}`,
  );
}

function columnsForTable(databaseUrl, tenantId, table) {
  const result = runPsql(
    databaseUrl,
    tenantId,
    `SELECT string_agg(format('%I', column_name), ', ' ORDER BY ordinal_position)
       FROM information_schema.columns
      WHERE table_schema = 'public'
        AND table_name = ${`'${table.replaceAll("'", "''")}'`};`,
  ).trim();

  if (!result) {
    throw new Error(`No columns found for restore table ${table}`);
  }
  return result;
}

function writeExport(databaseUrl, tenantId, outputPath) {
  const schema = fs.readFileSync(schemaPath, 'utf8');
  const manifest = buildTenantRestoreManifest(schema);
  const outputDirectory = path.dirname(path.resolve(outputPath));
  fs.mkdirSync(outputDirectory, { recursive: true });

  const chunks = [
    '-- Generated by tools/tenant-restore/export-tenant-data.sh.\n',
    '-- Every COPY source is tenant-filtered; this is not a pg_dump output.\n',
    'BEGIN;\n\n',
  ];

  for (const definition of manifest.definitions) {
    const columns = columnsForTable(databaseUrl, tenantId, definition.table);
    chunks.push(
      `COPY public.${quoteIdentifier(definition.table)} (${columns}) FROM STDIN WITH (FORMAT csv);\n`,
    );
    chunks.push(
      copyForTenant(databaseUrl, tenantId, renderExportQuery(definition)),
    );
    chunks.push('\\.\n\n');
  }

  chunks.push('COMMIT;\n');
  fs.writeFileSync(outputPath, chunks.join(''));
}

const [, , databaseUrl, tenantId, outputPath] = process.argv;
if (!databaseUrl || !tenantId || !outputPath) {
  process.stderr.write(
    'Usage: export-tenant-data.mjs <database_url> <tenant_id> <output_sql_file>\n',
  );
  process.exit(1);
}
if (!UUID_PATTERN.test(tenantId)) {
  process.stderr.write('target tenant id must be a UUID\n');
  process.exit(1);
}

try {
  writeExport(databaseUrl, tenantId, outputPath);
} catch (error) {
  process.stderr.write(`[tenant-restore] ${error.message}\n`);
  process.exitCode = 1;
}
