#!/usr/bin/env bash
# Creates or patches gitignored apps/core-api/.env with local-only Cloud Agent fixtures.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
ENV_FILE="${ROOT}/apps/core-api/.env"

SECRET_ENCRYPTION_KEY="$(
  node -e "process.stdout.write(Buffer.alloc(32, 7).toString('base64'))"
)"
CATALOG_HIT_HMAC_SECRET="acp-cloud-agent-local-catalog-hmac"

declare -A DEFAULTS=(
  [DATABASE_URL]="postgresql://acp_cloud:acp_cloud_local_only@127.0.0.1:5432/core_platform"
  [NODE_ENV]="development"
  [FIREBASE_PROJECT_ID]="auto-core-platform-vande"
  [SECRET_ENCRYPTION_KEY]="${SECRET_ENCRYPTION_KEY}"
  [CATALOG_HIT_HMAC_SECRET]="${CATALOG_HIT_HMAC_SECRET}"
)

env_has_key() {
  local key="$1"
  [[ -f "${ENV_FILE}" ]] && grep -q "^${key}=" "${ENV_FILE}"
}

if [[ ! -f "${ENV_FILE}" ]]; then
  cat >"${ENV_FILE}" <<EOF
# Generated by .cursor/scripts/cloud-agent-write-env.sh (local Cloud Agent only).
DATABASE_URL=${DEFAULTS[DATABASE_URL]}
NODE_ENV=${DEFAULTS[NODE_ENV]}
FIREBASE_PROJECT_ID=${DEFAULTS[FIREBASE_PROJECT_ID]}
SECRET_ENCRYPTION_KEY=${DEFAULTS[SECRET_ENCRYPTION_KEY]}
CATALOG_HIT_HMAC_SECRET=${DEFAULTS[CATALOG_HIT_HMAC_SECRET]}
EOF
  exit 0
fi

append=()
for key in DATABASE_URL NODE_ENV FIREBASE_PROJECT_ID SECRET_ENCRYPTION_KEY CATALOG_HIT_HMAC_SECRET; do
  if ! env_has_key "${key}"; then
    append+=("${key}=${DEFAULTS[$key]}")
  fi
done

if ((${#append[@]} > 0)); then
  {
    echo ""
    echo "# Added by .cursor/scripts/cloud-agent-write-env.sh (missing keys only)."
    printf '%s\n' "${append[@]}"
  } >>"${ENV_FILE}"
fi
