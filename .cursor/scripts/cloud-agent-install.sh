#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "${ROOT}"

# shellcheck source=/dev/null
source "${ROOT}/.cursor/scripts/cloud-agent-export-env.sh"
# shellcheck source=/dev/null
source "${ROOT}/.cursor/scripts/cloud-agent-ensure-node.sh"

ensure_node_matches_nvmrc "${ROOT}"

bash "${ROOT}/.cursor/scripts/cloud-agent-start.sh"

npm ci --prefer-offline --no-audit --no-fund

npm exec --workspace=core-web -- playwright install --with-deps chromium

npm exec --workspace=core-api -- prisma generate

bash "${ROOT}/.cursor/scripts/cloud-agent-write-env.sh"

DATABASE_URL="${DATABASE_URL}" npm exec --workspace=core-api -- prisma migrate deploy

DATABASE_URL="${ACP_E2E_DATABASE_URL}" npm exec --workspace=core-api -- prisma migrate deploy

sudo tee /etc/profile.d/acp-cloud-agent.sh >/dev/null <<EOF
# Auto Core Platform Cloud Agent environment (generated by cloud-agent-install.sh)
# shellcheck disable=SC1091
. "${ROOT}/.cursor/scripts/cloud-agent-export-env.sh"
EOF
